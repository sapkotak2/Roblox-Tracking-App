# ---------------- front arm: elbow out, fist raised in front of the face ----------------
front = sp.layer()
front.poly('s', [(25, 22), (32, 22), (33, 29), (29, 30)]).v('S', 26, 24, 29).px('T', (30, 23), (31, 24))
front.poly('s', [(29, 28), (33, 28), (36, 20), (32, 19)]).v('S', 30, 24, 28)
front.h('w', 31, 35, 20).h('W', 31, 35, 21)
